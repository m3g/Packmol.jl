#=
Shared geometry for the "compact" (Wigner-Seitz) representation of a
periodic cell, used by both the rhombic dodecahedron (dodecahedron.jl) and
the truncated octahedron (octahedron.jl): both are literally defined as the
Wigner-Seitz cell of the lattice generated by their own `unitcell` columns
(FCC for the dodecahedron, BCC for the octahedron), and — because both
conventions deliberately use a Minkowski-reduced (shortest-vectors) basis
for that lattice — the true nearest periodic image of any point is always
among the 27 combinations of the three lattice vectors' -1/0/+1 multiples.
That search is therefore exactly the same code regardless of which shape's
`unitcell` it's given; only the `unitcell` matrix itself differs between the
two box types.
=#

#=
    _nearest_periodic_image(x::SVector{3,T}, unitcell::AbstractMatrix, center::SVector{3,T}) where {T}

Remaps `x` to the periodic image closest to `center` — the Wigner-Seitz
fundamental domain of the cell generated by `unitcell`'s columns — by brute
force over all 27 combinations of the three lattice vectors' -1/0/+1
multiples. Correct (not just a heuristic) for any Minkowski-reduced basis,
which is what both `dodecahedral_unitcell` and `octahedral_unitcell` build;
for an arbitrary/unreduced `unitcell` it's a reasonable approximation, same
caveat as any other minimum-image-convention implementation.
=#
function _nearest_periodic_image(x::SVector{3,T}, unitcell::AbstractMatrix, center::SVector{3,T}) where {T}
    rel = x - center
    v1 = SVector{3,T}(unitcell[1, 1], unitcell[2, 1], unitcell[3, 1])
    v2 = SVector{3,T}(unitcell[1, 2], unitcell[2, 2], unitcell[3, 2])
    v3 = SVector{3,T}(unitcell[1, 3], unitcell[2, 3], unitcell[3, 3])
    best = rel
    best_dist2 = sum(abs2, rel)
    for n1 in -1:1, n2 in -1:1, n3 in -1:1
        (n1 == 0 && n2 == 0 && n3 == 0) && continue
        cand = rel + n1 * v1 + n2 * v2 + n3 * v3
        dist2 = sum(abs2, cand)
        if dist2 < best_dist2
            best = cand
            best_dist2 = dist2
        end
    end
    return best + center
end

#
# Throw an error if an atom of a fixed molecule is outside the periodic cell, as Fortran
# Packmol does: it is most likely an error in the input (e.g. a cell too small for the
# fixed molecule, or a fixed position given for another cell). An atom is inside the cell
# if it is inside the parallelepiped of the cell vectors centered at `unitcell_center`, or
# closer to the center than to all its periodic images (the shape of the dodecahedral and
# octahedral cells). For orthorhombic cells both regions are the same box.
#
function _check_fixed_inside_cell(packmol_system::PackmolSystem{D,T}) where {D,T}
    unitcell, center = packmol_system.unitcell, packmol_system.unitcell_center
    (isnothing(unitcell) || isnothing(center)) && return nothing
    ucell = SMatrix{D,D,T}(unitcell)
    inv_ucell = inv(ucell)
    for (itype, st) in enumerate(packmol_system.structure_types)
        st.fixed.fixed || continue
        # The reference coordinates of fixed molecules are their atom positions
        for (iatom, x) in enumerate(st.reference_coordinates)
            _inside_cell(x, ucell, inv_ucell, center) && continue
            position = join((@sprintf("%.3f", xi) for xi in x), " ")
            throw(ArgumentError("""\n
                Fixed molecules are outside the periodic cell: atom $iatom of structure $itype ($(basename(st.filename)))
                is at position ($position), after placing the molecule at its fixed position and orientation.
                Check the size of the cell and the position of the fixed molecule.

            """))
        end
    end
    return nothing
end

# Atoms within `_inside_cell_tolerance` (Å) of the cell are inside: the coordinates of PDB
# files have a precision of 0.001 Å, so atoms on the faces of the cell (as in crystal
# structures) can be slightly outside it.
const _inside_cell_tolerance = 0.01

function _inside_cell(x::SVector{D,T}, ucell::SMatrix{D,D,T}, inv_ucell::SMatrix{D,D,T}, center::SVector{D,T}) where {D,T}
    tol = T(_inside_cell_tolerance)
    f = inv_ucell * (x - center)
    all(i -> abs(f[i]) <= T(0.5) + tol / norm(ucell[:, i]), 1:D) && return true
    D == 3 || return false
    return norm(_nearest_periodic_image(x, ucell, center) - x) <= tol
end
